-- 001_init: core commerce, fulfilment and form tables.
-- Additive only. Money is stored as integer paise (₹1 = 100 paise).

CREATE TABLE IF NOT EXISTS customers (
  id          bigserial PRIMARY KEY,
  email       text NOT NULL,
  name        text NOT NULL,
  phone       text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT customers_email_lower CHECK (email = lower(email)),
  CONSTRAINT customers_email_unique UNIQUE (email)
);

-- Stock per sellable variant. A variant with no row here cannot be bought.
CREATE TABLE IF NOT EXISTS inventory (
  product_slug  text NOT NULL,
  variant_id    text NOT NULL,
  quantity      integer NOT NULL CHECK (quantity >= 0),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (product_slug, variant_id)
);

CREATE TABLE IF NOT EXISTS orders (
  id                   bigserial PRIMARY KEY,
  order_number         text NOT NULL UNIQUE,
  -- Unguessable token used in the customer's order-status URL.
  public_token         uuid NOT NULL UNIQUE,
  -- Generated by the browser per checkout attempt, so a double-submitted
  -- checkout returns the same pending order instead of creating another.
  client_request_id    uuid UNIQUE,
  customer_id          bigint NOT NULL REFERENCES customers(id),
  status               text NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'paid', 'failed', 'cancelled')),
  -- Set when something about a paid order needs a human (e.g. oversold stock,
  -- amount mismatch). Never cleared automatically.
  attention_reason     text,
  currency             text NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
  subtotal_paise       integer NOT NULL CHECK (subtotal_paise > 0),
  shipping_paise       integer NOT NULL CHECK (shipping_paise >= 0),
  total_paise          integer NOT NULL CHECK (total_paise = subtotal_paise + shipping_paise),
  shipping_address     jsonb NOT NULL,
  razorpay_order_id    text UNIQUE,
  razorpay_payment_id  text UNIQUE,
  payment_method       text,
  failure_reason       text,
  paid_at              timestamptz,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT orders_paid_has_payment CHECK (
    status <> 'paid' OR (razorpay_payment_id IS NOT NULL AND paid_at IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS orders_status_created_idx ON orders (status, created_at DESC);
CREATE INDEX IF NOT EXISTS orders_customer_idx ON orders (customer_id);

CREATE TABLE IF NOT EXISTS order_items (
  id                bigserial PRIMARY KEY,
  order_id          bigint NOT NULL REFERENCES orders(id),
  product_slug      text NOT NULL,
  variant_id        text NOT NULL,
  name              text NOT NULL,
  variant_label     text NOT NULL,
  unit_price_paise  integer NOT NULL CHECK (unit_price_paise > 0),
  quantity          integer NOT NULL CHECK (quantity > 0),
  UNIQUE (order_id, product_slug, variant_id)
);

-- Durable post-payment steps. One row per (order, task); the unique key plus
-- the claim/lease columns guarantee each step runs at most once at a time and
-- never re-runs after it has succeeded.
CREATE TABLE IF NOT EXISTS order_tasks (
  id             bigserial PRIMARY KEY,
  order_id       bigint NOT NULL REFERENCES orders(id),
  task           text NOT NULL CHECK (task IN (
                   'customer_email', 'owner_email', 'shiprocket_order', 'shipping_alert_email')),
  status         text NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'processing', 'succeeded', 'failed', 'needs_attention')),
  attempts       integer NOT NULL DEFAULT 0,
  max_attempts   integer NOT NULL DEFAULT 5,
  locked_until   timestamptz,
  next_run_at    timestamptz NOT NULL DEFAULT now(),
  last_error     text,
  result         jsonb,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (order_id, task)
);
CREATE INDEX IF NOT EXISTS order_tasks_due_idx ON order_tasks (status, next_run_at);

-- Every verified Razorpay webhook, keyed by Razorpay's event id, so a
-- re-delivered event is recognised and skipped.
CREATE TABLE IF NOT EXISTS payment_events (
  event_id      text PRIMARY KEY,
  event_type    text NOT NULL,
  razorpay_order_id text,
  payload       jsonb NOT NULL,
  received_at   timestamptz NOT NULL DEFAULT now(),
  processed_at  timestamptz
);

CREATE TABLE IF NOT EXISTS newsletter_subscribers (
  id            bigserial PRIMARY KEY,
  email         text NOT NULL UNIQUE CHECK (email = lower(email)),
  status        text NOT NULL DEFAULT 'subscribed' CHECK (status IN ('subscribed', 'unsubscribed')),
  source        text NOT NULL DEFAULT 'website',
  consented_at  timestamptz NOT NULL DEFAULT now(),
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS contact_messages (
  id           bigserial PRIMARY KEY,
  name         text NOT NULL,
  email        text NOT NULL,
  message      text NOT NULL,
  notified_at  timestamptz,
  notify_error text,
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- Fixed-window rate limiting for public forms. Keys hold a salted hash of the
-- client IP, never the raw address.
CREATE TABLE IF NOT EXISTS rate_limits (
  key           text NOT NULL,
  window_start  timestamptz NOT NULL,
  hits          integer NOT NULL DEFAULT 1,
  PRIMARY KEY (key, window_start)
);
